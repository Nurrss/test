-- Ученик забыл пароль — нужно, чтобы он сам мог посмотреть свой текущий пароль,
-- и чтобы учитель тоже мог его увидеть/сбросить.
--
-- Supabase Auth (GoTrue) хранит пароль только хешированным и НИКОГДА не отдаёт
-- его обратно ни через один API — ни admin, ни обычный. Поэтому единственный
-- способ показать "полный пароль" — сохранить его копию открытым текстом в
-- profiles в момент, когда он задаётся (create-student / reset-student-password
-- Edge Functions, единственные места, которые вообще знают пароль в открытом виде).
--
-- RLS менять не нужно: существующие политики "own profile" (id = auth.uid())
-- и "teacher sees all profiles" уже разрешают select всех колонок нужных строк —
-- они не колоночные, а построчные.

alter table profiles add column if not exists password_plain text;

comment on column profiles.password_plain is
  'Пароль открытым текстом — только для восстановления доступа ученику/учителю. '
  'Заполняется исключительно Edge Functions (create-student, reset-student-password) '
  'в момент задания пароля; для аккаунтов, созданных до этого патча, будет NULL, '
  'пока учитель не сбросит пароль через "Құпия сөзді ауыстыру".';
